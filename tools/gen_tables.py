"""Generate engine/src/game/stage_tables.cpp from the original binary.

Extracts the field-loading tables used by fldread_prc / npc_get_stgmapctl:
  - area -> event file name        (pointer table referenced at 0x43828)
  - area -> first map number       (s16 table referenced at 0x448f8)
  - map number -> collision file   (pointer table referenced at 0x43848)
  - NPC model index -> model file  (pointer table via 0xcf0ac, used by npc_setup)
  - treasure item pools            (_TBOX_TABLE_A/B/C, _TBOX_PAIR_TABLE_A/B/C)
  - battle stages / models          (_btlflrname via 0xcf0d4, _btlcplname via 0xcf0d0)
  - battle formations / positions   (_btl_init_index via 0xcf0cc, _btlinitpos via 0xcf040)
  - menu pictures                    (MuTex_GetTexInfo's sheet-0 rectangles at 0xc9fb0)
Only file names and numbers are copied.

usage: gen_tables.py <ChaosRingsHD binary> <output .cpp>
"""
import struct
import sys

NUM_AREAS = 28
NUM_MAPS = 178  # 0..113 the fields and towns, 114..177 the 64 puzzle stages (area 1, j001_p01)
NUM_NPC_MODELS = 305  # 0..196 field NPCs and props, 197.. the story scenes' boss and party models
NUM_TEX2D_IMAGES = 254
NUM_ACTION_FILES = 205
NUM_BATTLE_STAGES = 19
NUM_BATTLE_MODELS = 89


def main():
    data = open(sys.argv[1], "rb").read()
    ncmds = struct.unpack_from("<I", data, 16)[0]
    off, segs = 28, []
    for _ in range(ncmds):
        cmd, size = struct.unpack_from("<II", data, off)
        if cmd == 1:
            vm, vsz, fo, fsz = struct.unpack_from("<IIII", data, off + 24)
            segs.append((vm, fo, fsz))
        off += size

    def rd(addr, n):
        for vm, fo, fsz in segs:
            if vm <= addr < vm + fsz:
                return data[fo + addr - vm:fo + addr - vm + n]
        raise ValueError(hex(addr))

    u32 = lambda a: struct.unpack("<I", rd(a, 4))[0]

    def cstr(a):
        out = bytearray()
        while True:
            c = rd(a + len(out), 1)
            if c == b"\0":
                return out.decode("ascii")
            out += c

    evt_tab = u32(u32(0x43828))
    map_tab = u32(u32(0x43848))
    base_tab = u32(u32(0x448f8))
    events = [cstr(u32(evt_tab + 4 * i)) for i in range(NUM_AREAS)]
    bases = [struct.unpack("<h", rd(base_tab + 2 * i, 2))[0] for i in range(NUM_AREAS)]
    maps = [cstr(u32(map_tab + 4 * i)) for i in range(NUM_MAPS)]
    s32 = lambda a: struct.unpack("<i", rd(a, 4))[0]
    tbox = [[[s32(t + (row * 13 + i) * 4) for i in range(13)] for row in range(10)]
            for t in (0xca9a0, 0xcabb0, 0xcadc0)]          # A, B, C
    pair = [[[[s32(t + lvl * 32 + route * 8 + k * 4) for k in range(2)] for route in range(4)] for lvl in range(10)]
            for t in (0xcafd0, 0xcb110, 0xcb250)]          # A, B, C
    step_run = [[s32(0xca900 + (r * 2 + k) * 4) for k in range(2)] for r in range(4)]   # FOOTSTEP_FRAME (run)
    step_walk = [[s32(0xca960 + (r * 2 + k) * 4) for k in range(2)] for r in range(4)]  # _FOOTSTEP_FRAME (walk)
    step_se = [[s32(0xca920 + (t * 3 + k) * 4) for k in range(3)] for t in range(5)]    # FOOTSTEP_SE
    npc_tab = u32(0xcf0ac)
    npc_models = [cstr(u32(npc_tab + 4 * i)) for i in range(NUM_NPC_MODELS)]
    img_tab = u32(u32(0x7c640))                                           # EvtTex2d's image list
    images = [cstr(u32(img_tab + 4 * i)) for i in range(NUM_TEX2D_IMAGES)]
    act_tab = u32(u32(0x7e1d4))                                           # EvtLoadAct's action list
    act_files = [cstr(u32(act_tab + 4 * i)) for i in range(NUM_ACTION_FILES)]
    s16 = lambda a: struct.unpack("<h", rd(a, 2))[0]
    btl_stages = [cstr(u32(u32(0xcf0d4) + 4 * i)) for i in range(NUM_BATTLE_STAGES)]
    btl_models = [cstr(u32(u32(0xcf0d0) + 4 * i)) for i in range(NUM_BATTLE_MODELS)]
    formation_codes = [s16(u32(0xcf0cc) + 2 * i) for i in range(48)]
    menu_pictures = [[s16(0xc9fb0 + 8 * i + 2 * k) for k in range(4)] for i in range(156)]
    positions = [[[s16(u32(0xcf040) + (f * 12 + k) * 4 + c * 2) for c in range(2)] for k in range(12)] for f in range(16)]

    q = lambda s: '"' + s + '"'
    lines = [
        "// Generated by tools/gen_tables.py from the original binary — do not edit.",
        "// Field-loading tables: see docs/FORMATS.md (\"Field maps\", \"Event files\").",
        '#include "game/stage_tables.hpp"',
        "",
        "namespace cr {",
        "",
        f"const char* const kAreaEventFile[kNumAreas] = {{{', '.join(q(e) for e in events)}}};",
        "",
        f"const short kAreaFirstMap[kNumAreas] = {{{', '.join(str(b) for b in bases)}}};",
        "",
        "const char* const kMapCollisionFile[kNumMaps] = {",
    ]
    for i in range(0, NUM_MAPS, 6):
        lines.append("    " + ", ".join(q(m) for m in maps[i:i + 6]) + ",")
    lines += ["};", "", "const char* const kNpcModelFile[kNumNpcModels] = {"]
    for i in range(0, NUM_NPC_MODELS, 6):
        lines.append("    " + ", ".join(q(m) for m in npc_models[i:i + 6]) + ",")
    lines += ["};", "", "const char* const kTex2dImage[kNumTex2dImages] = {"]
    for i in range(0, NUM_TEX2D_IMAGES, 5):
        lines.append("    " + ", ".join(q(m) for m in images[i:i + 5]) + ",")
    lines += ["};", "", "const char* const kActionFile[kNumActionFiles] = {"]
    for i in range(0, NUM_ACTION_FILES, 6):
        lines.append("    " + ", ".join(q(m) for m in act_files[i:i + 6]) + ",")
    lines += ["};", "", "const char* const kBattleStageFile[kNumBattleStages] = {"]
    for i in range(0, NUM_BATTLE_STAGES, 6):
        lines.append("    " + ", ".join(q(m) for m in btl_stages[i:i + 6]) + ",")
    lines += ["};", "", "const char* const kBattleModelFile[kNumBattleModels] = {"]
    for i in range(0, NUM_BATTLE_MODELS, 6):
        lines.append("    " + ", ".join(q(m) for m in btl_models[i:i + 6]) + ",")
    lines += ["};", "", "const short kBattleFormationCode[48] = {" + ", ".join(map(str, formation_codes)) + "};",
              "", "const short kBattlePosition[16][12][2] = {"]
    for f in positions:
        lines.append("    {" + ", ".join("{%d, %d}" % tuple(e) for e in f) + "},")
    lines += ["};", "", "const short kMenuPicture[156][4] = {"]
    for i in range(0, 156, 6):
        lines.append("    " + ", ".join("{%d, %d, %d, %d}" % tuple(r) for r in menu_pictures[i:i + 6]) + ",")
    lines += ["};", "", "const short kTreasureItems[3][10][13] = {"]
    for t in tbox:
        lines.append("    {" + ", ".join("{" + ", ".join(map(str, row)) + "}" for row in t) + "},")
    lines += ["};", "", "const short kTreasurePairs[3][10][4][2] = {"]
    for t in pair:
        lines.append("    {" + ", ".join("{" + ", ".join("{%d, %d}" % tuple(r) for r in lvl) + "}" for lvl in t) + "},")
    lines += ["};", "",
              "const short kFootstepFrameRun[4][2] = {" + ", ".join("{%d, %d}" % tuple(r) for r in step_run) + "};",
              "const short kFootstepFrameWalk[4][2] = {" + ", ".join("{%d, %d}" % tuple(r) for r in step_walk) + "};",
              "const short kFootstepSound[5][3] = {" + ", ".join("{%d, %d, %d}" % tuple(t) for t in step_se) + "};",
              "", "} // namespace cr", ""]
    open(sys.argv[2], "w").write("\n".join(lines))
    print(f"wrote {sys.argv[2]}: {NUM_AREAS} areas, {NUM_MAPS} maps, {NUM_NPC_MODELS} NPC models, {NUM_TEX2D_IMAGES} images, {NUM_ACTION_FILES} action files")


if __name__ == "__main__":
    main()
